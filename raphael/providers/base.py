from typing import Callable, Protocol

from ..contracts import Cancellation, ChatRequest, Result, SpeechRequest, TranscriptionRequest


class ChatProvider(Protocol):
    models: list[str]
    def start(self) -> None: ...
    def generate(self, request: ChatRequest, cancel: Cancellation,
                 on_delta: Callable[[str], None]) -> Result: ...
    def close(self) -> None: ...


class VoiceProvider(Protocol):
    voices: dict[str, dict[str, str]]
    def start(self) -> None: ...
    def synthesize(self, request: SpeechRequest, cancel: Cancellation) -> Result: ...
    def close(self) -> None: ...


class TranscriptionProvider(Protocol):
    def start(self) -> None: ...
    def transcribe(self, request: TranscriptionRequest, cancel: Cancellation,
                   on_delta: Callable[[str], None]) -> Result: ...
    def close(self) -> None: ...
